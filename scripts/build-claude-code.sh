#!/usr/bin/env bash
# Build the Claude Code plugin package from canonical sources.
# Stages into a temporary directory, validates, then replaces dist/claude-code/dev-harness.
# dist/ is never edited in place and is never a source of truth.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$ROOT/dist/claude-code/dev-harness"
VERSION="${DEV_HARNESS_VERSION:-0.1.0}"
VALIDATE="$ROOT/scripts/validate.py"

[ -f "$VALIDATE" ] || { echo "missing $VALIDATE" >&2; exit 1; }
command -v python3 >/dev/null 2>&1 || { echo "python3 is required to build" >&2; exit 1; }

python3 "$VALIDATE" --source-only "$ROOT" || { echo "source validation failed" >&2; exit 1; }

STAGE="$(mktemp -d)"
cleanup() { rm -rf "$STAGE"; }
trap cleanup EXIT
PKG="$STAGE/dev-harness"

copy_tree() {
  local src="$1"
  local dst="$2"
  mkdir -p "$dst"
  cp -R "$src/." "$dst/"
  find "$dst" -name .gitkeep -delete
}

mkdir -p "$PKG"
copy_tree "$ROOT/.agents" "$PKG/agents"
copy_tree "$ROOT/.skills" "$PKG/skills"
copy_tree "$ROOT/.commands" "$PKG/commands"
copy_tree "$ROOT/templates" "$PKG/templates"
copy_tree "$ROOT/profiles" "$PKG/profiles"
mkdir -p "$PKG/scripts"
cp "$ROOT/scripts/validate.py" "$PKG/scripts/validate.py"
cp "$ROOT/scripts/doctor.sh" "$PKG/scripts/doctor.sh"
chmod +x "$PKG/scripts/doctor.sh" "$PKG/scripts/validate.py"

# Byte-for-byte check of copied trees against sources (excluding generated files).
for pair in ".agents:agents" ".skills:skills" ".commands:commands" "templates:templates" "profiles:profiles"; do
  src="$ROOT/${pair%%:*}"
  dst="$PKG/${pair##*:}"
  diff -rq "$src" "$dst" --exclude=.gitkeep >/dev/null || {
    echo "copy mismatch: $src -> $dst" >&2
    exit 1
  }
done

mkdir -p "$PKG/.claude-plugin"
python3 - "$PKG" "$VERSION" "$ROOT" <<'PY'
import json, sys
from datetime import datetime, timezone
from pathlib import Path

pkg = Path(sys.argv[1])
version = sys.argv[2]
root = Path(sys.argv[3])

def names(folder, pattern):
    return sorted(p.stem for p in (pkg / folder).glob(pattern))

def skill_names():
    return sorted(p.parent.name for p in (pkg / "skills").glob("*/SKILL.md"))

def profile_names():
    return sorted(p.stem for p in (pkg / "profiles").glob("*.yaml"))

manifest = {
    "name": "dev-harness",
    "version": version,
    "license": "MIT",
    "generated": True,
    "generated_at": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
    "source": "scripts/build-claude-code.sh",
    "runtime": {
        "primary": "claude-code",
        "load": "claude --plugin-dir dist/claude-code/dev-harness --agent coordinator",
        "command_prefix": "/dev-harness:",
        "minimum_version": "unverified",
    },
    "inventory": {
        "agents": names("agents", "*.md"),
        "commands": names("commands", "*.md"),
        "skills": skill_names(),
        "profiles": profile_names(),
        "templates": sorted(str(p.relative_to(pkg / "templates")) for p in (pkg / "templates").rglob("*.md")),
    },
}
(pkg / "harness-manifest.json").write_text(
    json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
)
(root / "harness-manifest.json").write_text(
    json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
)
plugin = {
    "name": "dev-harness",
    "version": version,
    "description": "Portable AI-assisted development kit: coordinator plus specialist agents, skills and work commands with owner-authorized delivery.",
    "author": {"name": "malka"},
    "license": "MIT",
    "keywords": ["development", "agents", "coordinator", "qa", "review"],
}
(pkg / ".claude-plugin" / "plugin.json").write_text(
    json.dumps(plugin, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
)
(pkg / "GENERATED.txt").write_text(
    "Generated by scripts/build-claude-code.sh. Do not edit. Change canonical sources and rebuild.\n",
    encoding="utf-8",
)
print(f"manifest     version {version}")
print(f"agents       {len(manifest['inventory']['agents'])} files")
print(f"commands     {len(manifest['inventory']['commands'])} files")
print(f"skills       {len(manifest['inventory']['skills'])} files")
print(f"profiles     {len(manifest['inventory']['profiles'])} files")
print(f"templates    {len(manifest['inventory']['templates'])} files")
PY

python3 "$VALIDATE" "$PKG" || { echo "package validation failed" >&2; exit 1; }

mkdir -p "$(dirname "$OUT")"
rm -rf "$OUT"
mkdir -p "$(dirname "$OUT")"
cp -R "$PKG" "$OUT"

python3 "$VALIDATE" "$ROOT" || { echo "kit coverage validation failed after replace" >&2; exit 1; }
echo "wrote        $OUT"
